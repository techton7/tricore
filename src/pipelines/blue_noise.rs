#[cfg(test)]
mod tests {
    use super::*;
    use std::f64::consts::PI;

    #[test]
    fn blue_noise_lut_has_exact_uniform_histogram() {
        let mut hist = [0u32; 256];
        for &v in &BLUE_NOISE_64X64 {
            hist[v as usize] += 1;
        }
        for (val, &count) in hist.iter().enumerate() {
            assert_eq!(count, 16, "expected 16 occurrences of {val}, got {count}");
        }
    }

    #[test]
    fn blue_noise_lut_has_blue_noise_spectrum() {
        const N: usize = BLUE_NOISE_DIM as usize;
        const M: usize = N * N;
        let mean = BLUE_NOISE_64X64.iter().map(|&v| v as f64).sum::<f64>() / (M as f64);

        let mut row_re = [0.0f64; M];
        let mut row_im = [0.0f64; M];
        for y in 0..N {
            for kx in 0..N {
                let mut re = 0.0;
                let mut im = 0.0;
                for x in 0..N {
                    let ang = -2.0 * PI * (kx * x) as f64 / (N as f64);
                    let v = BLUE_NOISE_64X64[y * N + x] as f64 - mean;
                    re += v * ang.cos();
                    im += v * ang.sin();
                }
                row_re[y * N + kx] = re;
                row_im[y * N + kx] = im;
            }
        }

        let mut low_power = 0.0;
        let mut low_count = 0usize;
        let mut high_power = 0.0;
        let mut high_count = 0usize;
        for ky in 0..N {
            let fy = if ky <= N / 2 { ky as i32 } else { ky as i32 - N as i32 };
            for kx in 0..N {
                let fx = if kx <= N / 2 { kx as i32 } else { kx as i32 - N as i32 };
                let r2 = fx * fx + fy * fy;
                if r2 == 0 {
                    continue;
                }
                let mut re = 0.0;
                let mut im = 0.0;
                for y in 0..N {
                    let ang = -2.0 * PI * (ky * y) as f64 / (N as f64);
                    let c = ang.cos();
                    let s = ang.sin();
                    let rr = row_re[y * N + kx];
                    let ri = row_im[y * N + kx];
                    re += rr * c - ri * s;
                    im += rr * s + ri * c;
                }
                let power = (re * re + im * im) / (M as f64);
                if r2 <= 64 {
                    low_power += power;
                    low_count += 1;
                } else if r2 >= 256 {
                    high_power += power;
                    high_count += 1;
                }
            }
        }

        let low_avg = low_power / (low_count as f64);
        let high_avg = high_power / (high_count as f64);
        let ratio = high_avg / low_avg;
        assert!(
            ratio > 100.0,
            "expected strong blue-noise high/low power ratio > 100, got {ratio:.2} (low={low_avg:.2}, high={high_avg:.2})"
        );
    }
}
